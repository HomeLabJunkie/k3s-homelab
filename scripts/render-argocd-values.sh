#!/usr/bin/env bash
# Write the settings files that Argo CD's applications read from the private
# configuration repository (<app>/values.yaml), from config/cluster.env.
#
# config/cluster.env is the one place a setting is changed. Run this after
# changing it, then commit and push the configuration repository; Argo CD
# applies the result. The Secrets beside these files come from
# scripts/render-argocd-secrets.sh. Nothing here is secret.
#
# Usage:
#   scripts/render-argocd-values.sh           Write the files.
#   scripts/render-argocd-values.sh --check   Compare what would be written
#                                             with the files there now.
#                                             Writes nothing.
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$ROOT_DIR/config/cluster.env}"
CONFIG_REPO="${CONFIG_REPO:-$ROOT_DIR/../k3s-homelab-config}"

CHECK=false
case "${1:-}" in
  "") ;;
  --check) CHECK=true ;;
  *) echo "Usage: $0 [--check]" >&2; exit 2 ;;
esac

fail() { echo "ERROR: $*" >&2; exit 1; }

command -v python3 >/dev/null 2>&1 || fail "python3 command is required"
[[ -r "$ENV_FILE" ]] || fail "cluster environment file is missing: $ENV_FILE"
[[ -f "$CONFIG_REPO/.sops.yaml" ]] ||
  fail "configuration repository not found at $CONFIG_REPO (set CONFIG_REPO)"

set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

# Directory inside the configuration repository to write to, with a trailing
# slash. Empty is production; a test cluster's cluster.env sets "envs/test/".
CONFIG_PATH="${CONFIG_PATH:-${ARGOCD_APPS_CONFIG_PATH:-}}"
[[ -z "$CONFIG_PATH" || "$CONFIG_PATH" == */ ]] || fail "CONFIG_PATH must end with a slash: $CONFIG_PATH"

for var in BASE_DOMAIN ADMIN_EMAIL CLOUDFLARE_ORIGIN_IP CLOUDFLARE_ACCOUNT_ID; do
  [[ -n "${!var:-}" ]] || fail "$var is not set in $ENV_FILE"
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Prints the header every generated file starts with. $1 says what reads it.
header() {
  cat <<EOF
# Generated by scripts/render-argocd-values.sh in k3s-homelab from
# config/cluster.env. Do not edit: change cluster.env and run the script.
# $1
EOF
}

# Quotes a value as a YAML string (JSON is valid YAML).
quoted() { python3 -c 'import json, sys; print(json.dumps(sys.argv[1]))' "$1"; }

domain="$(quoted "$BASE_DOMAIN")"
# shellcheck disable=SC2153 # set in cluster.env
admin_email="$(quoted "$ADMIN_EMAIL")"
authelia_hostname="${AUTHELIA_HOSTNAME:-auth.${BASE_DOMAIN}}"
rancher_hostname="${RANCHER_HOSTNAME:-rancher.${BASE_DOMAIN}}"

# render <app>: writes stdin as that application's settings file.
render() {
  mkdir -p "$WORK/$1"
  cat >"$WORK/$1/values.yaml"
}

{ header "Read by the authelia application (charts/authelia)."
  echo "domain: $domain"
  echo "adminEmail: $admin_email"
} | render authelia

{ header "Read by the cert-manager-config application (charts/cert-manager-config)."
  echo "adminEmail: $admin_email"
  # A test cluster points this at Let's Encrypt's staging service, which has
  # no weekly certificate limit; its certificates are not trusted.
  if [[ -n "${ACME_SERVER:-}" ]]; then echo "acmeServer: $(quoted "$ACME_SERVER")"; fi
} | render cert-manager

{ header "Read by the cloudflared application (charts/cloudflared): Traefik's address."
  echo "originIP: $(quoted "$CLOUDFLARE_ORIGIN_IP")"
} | render cloudflared

# Where Longhorn sends volume backups: a CIFS share on the backup NAS, and
# the name of the Secret holding its login.
for var in BACKUP_NAS_IP LONGHORN_BACKUP_SHARE; do
  [[ -n "${!var:-}" ]] || fail "$var is not set in $ENV_FILE"
done
backup_login_name="${LONGHORN_BACKUP_CREDENTIAL_SECRET:-longhorn-backup-cifs}"
{ header "Read by the longhorn-config application (charts/longhorn-config)."
  printf 'backupTargetURL: %s\n' \
    "$(quoted "cifs://${BACKUP_NAS_IP}/${LONGHORN_BACKUP_SHARE}?cifsOptions=vers%3D3.0")"
  printf 'credentialSecret: %s\n' "$(quoted "$backup_login_name")"
} | render longhorn

{ header "Read by the monitoring-extras application (charts/monitoring-extras)."
  echo "cloudflareAccountId: $(quoted "$CLOUDFLARE_ACCOUNT_ID")"
} | render monitoring-extras

{ header "Added to apps/monitoring/values.yaml for the monitoring application."
  cat <<EOF
grafana:
  # Sends Grafana's server-side single sign-on calls for the Authelia hostname
  # straight to Traefik instead of out through Cloudflare, whose bot check can
  # reject non-browser clients.
  hostAliases:
    - ip: $(quoted "$CLOUDFLARE_ORIGIN_IP")
      hostnames:
        - $(quoted "$authelia_hostname")
EOF
} | render monitoring

{ header "Added to apps/rancher/values.yaml for the rancher application."
  echo "hostname: $(quoted "$rancher_hostname")"
} | render rancher

for app in routes trilium website; do
  { header "Read by the $app application (charts/$app)."
    echo "domain: $domain"
  } | render "$app"
done

{ header "Read by the vaultwarden application (charts/vaultwarden)."
  echo "domain: $domain"
  echo "adminEmail: $admin_email"
} | render vaultwarden

# A test cluster has no backup store and leaves the velero application out.
if [[ ",${ARGOCD_APPS_DISABLED:-}," != *",velero,"* ]]; then
  [[ -n "${UNRAID_IP:-}" ]] || fail "UNRAID_IP is not set in $ENV_FILE"
  { header "Added to apps/velero/values.yaml for the velero application."
    cat <<EOF
# A list in a later values file replaces the whole list, so the storage
# location is repeated here in full; only s3Url differs from the placeholder
# there. It is the Garage S3 store on the Unraid server (UNRAID_IP).
configuration:
  backupStorageLocation:
    - name: garage
      provider: aws
      bucket: k3s-velero
      default: true
      accessMode: ReadWrite
      credential:
        name: velero-garage-credentials
        key: cloud
      config:
        checksumAlgorithm: ""
        region: garage
        s3ForcePathStyle: "true"
        s3Url: $(quoted "${VELERO_S3_URL:-http://${UNRAID_IP}:3900}")
EOF
  } | render velero
fi

# True when the two files hold the same settings; comments do not count.
same_settings() {
  python3 -c '
import sys, yaml
sys.exit(0 if yaml.safe_load(open(sys.argv[1])) == yaml.safe_load(open(sys.argv[2])) else 1)' "$1" "$2"
}

mapfile -t FILES < <(cd "$WORK" && find . -name values.yaml | sed 's#^\./##' | sort)

status=0
for file in "${FILES[@]}"; do
  target="$CONFIG_REPO/${CONFIG_PATH}$file"
  if [[ "$CHECK" == true ]]; then
    if [[ ! -f "$target" ]]; then echo "  missing    ${CONFIG_PATH}$file"; status=1
    elif same_settings "$WORK/$file" "$target"; then echo "  same       ${CONFIG_PATH}$file"
    else echo "  DIFFERENT  ${CONFIG_PATH}$file"; status=1; fi
  elif [[ -f "$target" ]] && cmp -s "$WORK/$file" "$target"; then
    echo "unchanged: ${CONFIG_PATH}$file"
  else
    mkdir -p "$(dirname "$target")"
    cp "$WORK/$file" "$target"
    chmod 644 "$target"
    echo "written:   ${CONFIG_PATH}$file"
  fi
done

if [[ "$CHECK" == true ]]; then exit "$status"; fi
echo "Commit and push $CONFIG_REPO for Argo CD to apply any change."
